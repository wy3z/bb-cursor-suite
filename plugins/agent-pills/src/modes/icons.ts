export function modeIconOf(value: string | null | undefined): string {
  const trimmed = value?.trim() ?? "";
  if (/^[A-Z][A-Za-z0-9]*$/.test(trimmed)) return trimmed;
  return ALIASES[trimmed.toLowerCase()] ?? DEFAULT_MODE_ICON;
}
